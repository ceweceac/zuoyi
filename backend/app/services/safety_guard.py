"""提示词风控规避（基于 OpenAI 官方《使用政策》2025-10-29 版）。

优化用户创作 prompt 时，主动识别并改写可能触发模型（尤其 GPT-image-2）内容审核
的元素，在保留用户核心创意的前提下规避被拒。规则严格依据官方政策原文 4 大类，
不是经验臆测。

用法：optimize() 把 SAFETY_RULES 拼进 system prompt，让 LLM 优化时一并规避。
另提供 quick_scan() 做轻量本地预判（是否含明显雷区词），用于日志/提示。
"""

# 规避规则块（注入优化器 system prompt）。依据官方政策 4 大保护原则。
SAFETY_RULES = (
    "\n\n【内容安全规避（基于 OpenAI 官方使用政策，必须遵守）】\n"
    "优化时，若用户输入涉及以下情形，在不破坏核心创意的前提下自动改写规避，"
    "并在结尾用一行『安全调整：』说明改了什么（无则不写）：\n"
    "1. 真人/名人肖像：不得以照片级逼真方式还原真实公众人物或具名真人"
    "（官方禁止『以可能混淆真伪的方式使用他人可识别形象』）。"
    "→ 把具体人名改为泛指特征（如『马斯克』→『一位中年科技企业家』）。\n"
    "2. 暴力/武器/恐怖：不得渲染血腥、伤害、武器制造使用、恐怖或仇恨暴力。"
    "→ 弱化为氛围/对峙/姿态（如『血流满地的尸体』→『紧张的对峙场面』，去掉具体武器细节）。\n"
    "3. 未成年人风险：绝不生成未成年人的性化、暴力或不适内容。"
    "→ 若涉及未成年人且场景不当，改为成年人或移除不当元素。\n"
    "4. 冒充/政治/违法：不得用于冒充他人、政治选举、非法活动、赌博、侵犯知识产权"
    "（含受版权保护的角色/品牌商标）。"
    "→ 版权角色原创化（『米老鼠』→『卡通老鼠形象』）、去掉真实品牌、避开政治人物与违法内容。\n"
    "底线：只改触线部分，保留用户其余创意与风格；改动要小、要透明。"
)

# 轻量本地预判用的雷区词（仅用于日志/统计，不做拦截——真正规避交给 LLM）
_RISK_HINTS = {
    "真人名人": ("马斯克", "特朗普", "拜登", "习近平", "明星", "名人", "真人脸", "本人照片"),
    "暴力武器": ("血腥", "尸体", "枪", "刀捅", "爆头", "杀", "恐怖袭击", "炸弹"),
    "未成年": ("萝莉", "幼女", "小学生", "儿童裸"),
    "版权品牌": ("米老鼠", "皮卡丘", "迪士尼", "漫威", "可口可乐", "苹果logo"),
}


def quick_scan(text: str) -> list:
    """轻量预判：返回命中的风险类别列表（仅供日志，不拦截）。"""
    s = (text or "")
    hits = []
    for cat, words in _RISK_HINTS.items():
        if any(w in s for w in words):
            hits.append(cat)
    return hits
